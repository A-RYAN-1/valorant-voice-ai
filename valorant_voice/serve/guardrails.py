"""Output and input guardrails: an inaudible watermark, an AI tag in the file, a text blocklist."""

import hashlib
import io
import re
from functools import lru_cache
from pathlib import Path

import numpy as np
import soundfile as sf

from .. import config

WATERMARK_LEVEL_DB = -24  # watermark level below the local speech level
DETECTION_Z = 5.0  # a clean signal reaches this by chance about 3 times in ten million
AI_TAG = "AI generated by Valorant Voice AI, an unofficial fan project"


def _sequence(length: int) -> np.ndarray:
    seed = int.from_bytes(hashlib.sha256(config.WATERMARK_KEY.encode()).digest()[:8], "big")
    return np.random.default_rng(seed).choice([-1.0, 1.0], size=length).astype("float32")


def _local_rms(samples: np.ndarray) -> np.ndarray:
    """Speech level over a 20 ms window, so the mark is quiet where the speech is quiet."""
    window = np.ones(480) / 480
    return np.sqrt(np.convolve(samples.astype("float64") ** 2, window, mode="same"))


def add_watermark(samples: np.ndarray) -> np.ndarray:
    """Spread-spectrum mark: a keyed +1/-1 noise sequence that follows the speech level, far below it."""
    samples = np.asarray(samples, dtype="float32")
    mark = _sequence(len(samples)) * _local_rms(samples) * 10 ** (WATERMARK_LEVEL_DB / 20)
    return samples + mark.astype("float32")


def watermark_score(samples: np.ndarray) -> float:
    """Correlation z-score against the keyed sequence: about 0 for clean audio, large when marked."""
    samples = np.asarray(samples, dtype="float64")
    weighted = samples * _local_rms(samples)
    spread = np.sqrt(np.sum(weighted**2))
    return float(np.dot(weighted, _sequence(len(samples))) / spread) if spread else 0.0


def is_watermarked(samples: np.ndarray) -> bool:
    return watermark_score(samples) > DETECTION_Z


def encode_wav(samples: np.ndarray, rate: int) -> bytes:
    """A 16-bit WAV with the watermark in the samples and the AI tag in the file's comment field."""
    buffer = io.BytesIO()
    with sf.SoundFile(buffer, "w", samplerate=rate, channels=1, format="WAV", subtype="PCM_16") as out:
        out.comment = AI_TAG
        out.write(add_watermark(samples))
    return buffer.getvalue()


def _normalise(text: str) -> str:
    return " ".join(re.sub(r"[^a-z0-9]+", " ", text.lower()).split())


@lru_cache
def _blocked_phrases() -> tuple[str, ...]:
    path = Path(config.BLOCKLIST_FILE) if config.BLOCKLIST_FILE else Path(__file__).with_name("blocklist.txt")
    lines = (line.strip() for line in path.read_text(encoding="utf-8").splitlines())
    return tuple(_normalise(line) for line in lines if line and not line.startswith("#"))


def is_blocked(text: str) -> bool:
    padded = f" {_normalise(text)} "
    return any(f" {phrase} " in padded for phrase in _blocked_phrases())
